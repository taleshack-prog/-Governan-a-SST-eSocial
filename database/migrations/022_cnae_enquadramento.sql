-- Fonte: ANEXO V do Decreto 3.048/99, na redacao do Decreto 10.410/2020 (vigente), CNAE 2.3.
-- Determinístico: grau 1=leve(RAT 1%), 2=medio(RAT 2%), 3=grave(RAT 3%).
