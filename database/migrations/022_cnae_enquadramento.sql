-- Natureza: ADITIVA. Idempotente (ON CONFLICT DO NOTHING).

CREATE TABLE IF NOT EXISTS cnae_enquadramento (
    cnae         VARCHAR(7)  PRIMARY KEY,           -- 7 digitos, sem pontuacao
    cnae_fmt     VARCHAR(10) NOT NULL,              -- formatado ####-#/##
    descricao    TEXT        NOT NULL,
    grau_risco   SMALLINT    NOT NULL CHECK (grau_risco BETWEEN 1 AND 3),
    aliquota_rat NUMERIC(3,2) NOT NULL CHECK (aliquota_rat IN (1.00, 2.00, 3.00)),
    fonte        VARCHAR(160) NOT NULL DEFAULT 'Anexo V Decreto 3.048/99 (red. Decreto 10.410/2020), CNAE 2.3',
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

